import streamlit as st
import datetime
st.title('🛒📊📈 Walmart Store Sales Prediction')

st.sidebar.title("User Input Features")

import pandas as pd
def user_input_features():
  date = st.sidebar.date_input('Enter the Date', min_value = datetime.date(2010,1,1))
  store_num = st.sidebar.number_input("Enter the store number")
  Holiday_Flag = st.sidebar.number_input("Enter the Holiday")
  Fuel_price = st.sidebar.number_input("Enter the Fuel Price")
  Temperature = st.sidebar.number_input("Enter the Temperature")
  CPI = st.sidebar.number_input("Enter the CPI number")
  unemployment = st.sidebar.number_input("Enter the unemployment")
  dic = { "Store":store_num,'Date': date,"Holiday_Flag": Holiday_Flag,"Temperature": Temperature, 'Fuel_Price': Fuel_price,"CPI": CPI,"Unemployment": unemployment}
  return pd.DataFrame(dic,index = [0])

result = user_input_features()

st.write(result)

date = pd.to_datetime(result['Date'])

result['Month'] = date.dt.month
result['Year'] = date.dt.year
result['Day'] = date.dt.day

import pickle

with open(r"model2.pkl",'rb') as file:
  dic = pickle.load(file)

X = result.drop(['Date'], axis = 1)

sc = dic['sc']
X = sc.transform(X)

model = dic['model']
pred = model.predict(X)

st.title("The Predicted result is")
st.write(pred)
